def cut(t):
    for k, rep in CUT_SCREENS.items():
        m = re.search(r"\n" + k + r":\{", t)
        if not m:
            raise SystemExit(f'LITE BUILD FAILED: screen {k} not found')
        i = m.start() + 1
        j = i + re.search(r"\n[a-z][a-z0-9_]*:\{", t[i:]).start() + 1
        t = t[:i] + rep + t[j:]
    for d, rep in CUT_DECLS.items():
        if t.count(d) != 1:
            raise SystemExit(f'LITE BUILD FAILED: {d} found {t.count(d)} times')
        i = t.find(d)
        j = i + re.search(r"\n(?=\S)", t[i:]).start() + 1
        t = t[:i] + rep + t[j:]
    return t


def build():
    t = cut(open(SRC, encoding='utf8').read())
    bad = []
    for old, new, n in P:
        c = t.count(old)
        if n == 0:
            continue
        if c != n:
            bad.append(f'expected {n}, found {c}: {old[:110]}')
            continue
        t = t.replace(old, new)
    if bad:
        print('LITE BUILD FAILED. The master changed where the lite edition differs:')
        for b in bad:
            print(' -', b)
        sys.exit(1)
    # Safety net: nothing in lite may still ask for or show the user's money figures.
    forbidden = ['How much Bitcoin do you hold?', 'Your wealth outside Bitcoin</h3>', 'Total amount you paid',
                 'Make a new allocation', 'How much capital are you considering?', 'FROM YOUR PLAN']
    leaks = [f for f in forbidden if f in t]
    if leaks:
        print('LITE BUILD FAILED. Full-edition text still reachable:', leaks)
        sys.exit(1)
    os.makedirs('lite', exist_ok=True)
    open(OUT, 'w', encoding='utf8').write(t)
    print(f'lite built: {len(P)} changes, {os.path.getsize(OUT)//1024} KB')




if __name__ == '__main__':
    build()
